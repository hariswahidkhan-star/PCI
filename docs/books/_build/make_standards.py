# Reference patterns. Longest-first matching matters: ISO/IEC 27701 must not be found as ISO/IEC 277.
# Patterns are deliberately wider than the obvious ones. A first version matched only ISO- and
# ISO/IEC-prefixed numbers and so missed IEC 62443 (no ISO prefix), the EU AI Act and the General
# Data Protection Regulation — the same failure as asserting a vocabulary instead of reading one, and
# a register that silently omits a regulation is worse than no register.
PATTERNS = [
    (r"\bISO(?:/IEC)?\s?\d{4,5}(?:[-‑]\d+)?\b", lambda m: re.sub(r"\s+", " ", m.group(0))),
    (r"(?<![/\w])IEC\s?\d{4,5}(?:[-‑]\d+)?\b", lambda m: re.sub(r"\s+", " ", m.group(0))),
    (r"\b(?:European Union's |EU )?AI Act\b", lambda m: "AI Act"),
    (r"\bGeneral Data Protection Regulation\b", lambda m: m.group(0)),
    (r"\bIFRS\s?\d{1,2}\b", lambda m: re.sub(r"\s+", " ", m.group(0))),
    (r"\bIAS\s?\d{1,2}\b", lambda m: re.sub(r"\s+", " ", m.group(0))),
    # Wrapped across lines in the manuscripts, so whitespace runs — never a literal space.
    (r"\bCombating\s+Bribery\s+of\s+Foreign\s+Public\s+Officials\b|\bOECD\s+Anti-Bribery\s+Convention\b",
     lambda m: "OECD Anti-Bribery Convention"),
    (r"\bFATF\b", lambda m: "FATF"),
    (r"\bEquator Principles\b", lambda m: m.group(0)),
    (r"\bIFC Performance Standards\b", lambda m: m.group(0)),
    (r"\bNIST\b", lambda m: m.group(0)),
    (r"\bOECD\b", lambda m: m.group(0)),
    (r"\bAACE\b", lambda m: m.group(0)),
    # Named bodies and instruments with no catalogue number. Wrapped across lines in the
    # manuscripts, so whitespace runs — never a literal space.
    (r"\bInstitute\s+of\s+Internal\s+Auditors\b", lambda m: "Institute of Internal Auditors"),
    (r"\bUN\s+Guiding\s+Principles\s+on\s+Business\s+and\s+Human\s+Rights\b",
     lambda m: "UN Guiding Principles on Business and Human Rights"),
    (r"(?<![\w-])NEC(?![\w-])", lambda m: "NEC"),
    (r"(?<![\w-])FIDIC(?![\w-])", lambda m: "FIDIC"),
    (r"(?<![\w-])JCT(?![\w-])", lambda m: "JCT"),
]


def scan(book: str) -> dict:
    """reference -> sorted list of 'D<n>' locations where it is discussed."""
    found = defaultdict(set)
    for f in sorted((ROOT / book / "manuscript").glob("domain-*.md")):
        dn = int(re.match(r"domain-(\d+)-", f.name).group(1))
        text = f.read_text(encoding="utf-8")
        for pat, norm in PATTERNS:
            for m in re.finditer(pat, text):
                found[norm(m)].add(dn)
    return {k: sorted(v) for k, v in found.items()}


def known() -> dict:
    return {ref: desc for _, entries in FAMILIES for ref, desc in entries}


def build(book: str, refs: dict) -> str:
    KNOWN = known()
    total = len(refs)
    L = [f"# Appendix F — Standards and frameworks referenced — {BOOKS[book]}", "",
         "> **Derived, not maintained.** Generated by `_build/make_standards.py` from the manuscripts",
         "> themselves. A standard referenced in a chapter and missing from this register fails the",
         "> build, so a reference cannot enter the corpus without being disclosed here.", "",
         f"This volume references **{total} documents, standards or frameworks**. Every one is *named*",
         "and *characterised* — never reproduced. No protected text, table, figure, clause, checklist or",
         "question from any of them appears in this volume; each is described at the level of its stated",
         "scope, in this programme's own words, and the treatment of the underlying subject is this",
         "programme's own. Where a chapter needs a number, it derives one rather than citing one.", "",
         "**Nothing here implies endorsement.** No standards body, institute, professional association",
         "or financial institution has reviewed, approved or endorsed this volume, the designation it",
         "supports, or this programme. A reference means only that the document exists and is relevant",
         "to the topic under discussion.", "",
         "**Editions are deliberately not stated.** No entry below carries an edition year or revision",
         "date. Standards are revised, withdrawn and superseded on their own schedules, and a citation",
         "to a superseded edition is worse than no citation, because it reads as authoritative while",
         "being wrong. Confirming the current edition of each document against the publisher's",
         "catalogue at the date of publication is a review task, and it is recorded as outstanding in",
         "`CORPUS_GATE_REPORT.md`. **A reader consulting any document below should obtain the current",
         "edition from its publisher.** Standards are copyright works and are not reproduced or",
         "redistributed by this programme.", ""]

    for family, entries in FAMILIES:
        rows = [(ref, desc) for ref, desc in entries if ref in refs]
        if not rows:
            continue
        L += [f"## {family}", "",
              "| Reference | Described in this volume as addressing | Discussed in |",
              "|---|---|---|"]
        for ref, desc in rows:
            where = ", ".join(f"D{d}" for d in refs[ref])
            L.append(f"| **{ref}** | {desc} | {where} |")
        L += [""]

    undisclosed = sorted(set(refs) - set(KNOWN))
    if undisclosed:
        L += ["## Undisclosed references — a defect", "",
              "The following appear in the manuscripts and are **not** characterised above. This is a",
              "build defect, not a finding about the standards:", ""]
        L += [f"- `{u}` ({', '.join('D' + str(d) for d in refs[u])})" for u in undisclosed] + [""]

    L += ["## What this register does not contain", "",
          "**No bibliography of textbooks or certification-body publications.** This volume is written",
          "from first principles and its worked examples are original, so there is no borrowed material",
          "to cite. Where a body of practice is discussed — cost-estimate classification, iterative",
          "delivery, portfolio governance — the discussion is of the *practice*, described in this",
          "programme's own words, and the reader is pointed to the owning body rather than given a",
          "paraphrase of its text.", "",
          "**No legal, tax or accounting authority.** The financial-reporting standards above are named",
          "where a chapter explains why a treatment matters, never to state what the treatment is in any",
          "jurisdiction. Every such passage carries the volume's standing caution: treatments are",
          "jurisdiction-specific, and the applicable position requires written advice for the specific",
          "entity and structure. The same applies to every legal question raised in the text.", ""]
    return "\n".join(L).rstrip() + "\n"


def main() -> int:
    check_only = "--check" in sys.argv
    KNOWN, defects = known(), 0
    all_refs = {}
    for book in BOOKS:
        refs = scan(book)
        all_refs[book] = refs
        undisclosed = sorted(set(refs) - set(KNOWN))
        if not check_only:
            (ROOT / book / "STANDARDS.md").write_text(build(book, refs), encoding="utf-8")
        print(f"{book}: {len(refs)} references"
              + (f" -> {book}/STANDARDS.md" if not check_only else " (audit only)"))
        for ref in sorted(refs):
            mark = "" if ref in KNOWN else "  <-- UNDISCLOSED"
            print(f"    {ref:<26} {', '.join('D' + str(d) for d in refs[ref])}{mark}")
        defects += len(undisclosed)

    unreferenced = sorted(set(KNOWN) - set().union(*(set(r) for r in all_refs.values())))
    if unreferenced:
        print(f"\ncharacterised but referenced by neither volume ({len(unreferenced)}): "
              + ", ".join(unreferenced))
        print("  (not a build failure, but the register should not claim engagement that is absent)")
        defects += len(unreferenced)
    print(f"\nopen standards-register defects: {defects}")
    return 1 if (check_only and defects) else 0


if __name__ == "__main__":
    raise SystemExit(main())
