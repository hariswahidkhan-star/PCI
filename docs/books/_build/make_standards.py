#!/usr/bin/env python3
"""Build each volume's standards-and-frameworks register, derived from the manuscripts.

Like the glossary, the appendices and the question bank, this is **derived** rather than maintained.
That matters more here than anywhere else: a register of standards is a disclosure document, and a
disclosure document that is edited by hand will eventually disagree with the text it discloses. This
one is generated by scanning every manuscript for references and cross-checking them against a
curated table of what each document addresses, so:

  * a standard referenced in a chapter but missing from the curated table **fails the check** — a new
    reference cannot enter the corpus without being disclosed here;
  * a standard in the table that no chapter references is reported as **unreferenced**, so the register
    cannot claim engagement the volumes do not have;
  * the "where" column is the live set of locations, so it cannot go stale.

**On editions, deliberately.** No entry states an edition year or revision date. That is not an
oversight and it is not laziness — it is the one claim this programme is not in a position to make.
Standards are revised, withdrawn and superseded on their own schedules, and a citation to a
superseded edition is worse than no citation at all, because it looks authoritative while being
wrong. Establishing the current edition of each document requires the publisher's catalogue at the
date of publication, which is a reviewer's task with access this build does not have. What the
register does assert is checkable from the text itself: which documents the volumes engage with,
what each is described as addressing, where each is discussed, and that none is reproduced.

Usage:  python3 make_standards.py            # write both registers
        python3 make_standards.py --check    # audit only; exit 1 on an undisclosed reference
"""
