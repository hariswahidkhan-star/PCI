               '| **J1** | The reviewer must decide for themselves whether something is *material*, '
               '*adverse* or *significant*, and no recorded threshold or recorded conclusion supplies '
               'the answer |\n'
               '| **J2** | The reviewer must judge whether an explanation, a response or an '
               'assessment is *complete*, *adequate* or *substantive* |\n'
               '| **J3** | The reviewer must reach a substantive conclusion **from** the evidence — '
