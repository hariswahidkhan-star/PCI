def family_of(item):
    it = re.sub(r'\s+', ' ', item.lower()).strip()
    m = EVID_HEAD.search(it)
    if m:
        words = m.group(1).split()
        head = [words[-1]]
        for w in reversed(words[:-1]):
            if w in ADJ_STOP:
                break
            head.insert(0, w)
        key = ' '.join(head[-3:])
    else:
        key = ' '.join(it.split()[:3])
    # Normalise the commonest plural forms so a family does not split on number alone.
    for pl, sg in (('records', 'record'), ('registers', 'register'), ('logs', 'log'),
                   ('statements', 'statement'), ('approvals', 'approval'),
                   ('declarations', 'declaration'), ('assessments', 'assessment'),
                   ('reports', 'report'), ('schedules', 'schedule'), ('disclosures', 'disclosure'),
                   ('certificates', 'certificate'), ('confirmations', 'confirmation'),
                   ('reconciliations', 'reconciliation'), ('versions', 'version'),
                   ('sign-offs', 'sign-off'), ('tests', 'test'), ('checks', 'check')):
        key = re.sub(r'\b%s\b' % pl, sg, key)
    # A leading modifier that says how the artefact was made, not what it is, splits families
    # that are the same artefact.
    key = re.sub(r'^(?:written|recorded|retained|dated|signed|issued|published|documented|final|'
                 r'complete|current)\s+', '', key)
    key = re.sub(r'\s+(?:and|or|of|to|with|for|by|the|a|an)$', '', key).strip()
    return SYNONYM.get(key, key)


