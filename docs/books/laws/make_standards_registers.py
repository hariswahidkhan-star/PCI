def role_of(law):
    """The accountable role from element 8, stripped of its purpose clause."""
    t = re.sub(r'\*\*|\*|`', '', flat(law['el'].get(8, '')))
    first = re.split(r'\.\s+(?=[A-Z])|;|\s+—\s+', t)[0]
    first = re.split(r'\s+(?:for|who|,\s*for|accountable for|responsible for)\s+', first)[0]
    first = strip_head(first.strip(' .,'))
    return clean_phrase(first, 70) or 'not stated'


