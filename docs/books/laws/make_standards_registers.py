def examines(el21, title):
    """The population or artefacts the test starts from, as element 21 names it."""
    t = re.sub(r'\*\*|\*', '', flat(el21))
    for end in (_END_STRICT, _END_LOOSE):
        for opening in _OPENINGS:
            m = re.search(opening + r'(.+?)' + end, t)
            if not m:
                continue
            got = clean_phrase(m.group(1))
            got = re.sub(r'\s+(and|or|from|of|with|by|to)$', '', got).strip(' ,;:—')
            if len(got) >= 5 and not BAD_SUBJECT.search(got):
                return got
    # Fall back to the object of the test's first lettered step.
    m = re.search(r'(?::\s*|\.\s+)\(a\)\s+(?:[A-Z][a-z\- ]{2,28}test:?\s*)?'
                  r'(?:obtains?|retrieves?|takes?|produces?|opens?|extracts?|lists?|names?|selects?|'
                  r'confirms?|finds?|rebuilds?|traces?|recomputes?|reads?|samples?|for )?\s*'
                  r'(.{10,80}?)(?:[;,]|\s+and\s+|\s+with\s+|\.)', t)
    if m:
        got = clean_phrase(m.group(1))
        got = re.sub(r'\s+(and|or|from|of|with|by|to|that)$', '', got).strip(' ,;:—')
        if len(got) >= 8 and not BAD_SUBJECT.search(got):
            return got
    # Fall back to the population named anywhere in the opening.
    m = re.search(r'\b(?:sample|population) of ([a-z][^,.;:]{5,45}?)(?:\s+and\s+|$|[,.;:])', t)
    if m:
        return clean_phrase(m.group(1))
    return 'the subject of the law — %s' % clean_phrase(title)


def reviewer_does(el21):
    t = flat(el21).lower()
    out = []
    for label, pat in VERB_LEXICON:
        m = re.search(pat, t)
        if m:
            out.append((m.start(), label))
    out.sort()
    seen, res = set(), []
    for _, label in out:
        if label not in seen:
            seen.add(label)
            res.append(label)
    return ' → '.join(res[:6]) if res else 'reads the record'


