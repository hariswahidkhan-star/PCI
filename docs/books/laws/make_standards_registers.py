               '| **J4** | The reviewer must apply a **counterfactual** — which decisions *would '
               'have* differed, which assumptions’ failure *would* change the conclusion |\n'
               '| **J5** | The reviewer must form a view about another person’s recorded state '
               'of mind |\n\n'
               'Otherwise the answer is **yes**: it follows from a document’s presence, a date '
