LAW_FILES = [FOUNDATIONAL] + list(CERT_FILES.values())
CRED_OF_FILE = {FOUNDATIONAL: 'FND', 'PCL_AI_STANDARDS.md': 'PCL', 'PFL_AI_STANDARDS.md': 'PFL',
                'PML_AI_STANDARDS.md': 'PML'}
CRED_NAME = {'FND': 'All three (Foundational)', 'PCL': 'PCL-AI', 'PFL': 'PFL-AI',
             'PML': 'PML-AI'}

HEADING = re.compile(r'^(#{2,6})\s+(.*)$', re.M)
LAW_HEADING = re.compile(r'^(#{2,6})\s+PCI STANDARD\s+(\S+)\s+—\s+(.*)$', re.M)
ELEMENT_MARK = re.compile(r'^\*\*(\d{1,2})\.\s+([^*]+?)\.\*\*', re.M)

STAMP = ('Generated by `make_standards_registers.py` from the four law files. **It is derived, not '
         'authoritative: it goes stale the moment a law file changes.** Re-run the generator after '
         'any edit, and read the law itself before relying on any row here.')


# ---------------------------------------------------------------------------- parsing

def read(path):
    with open(path, encoding='utf-8') as fh:
        return fh.read()


def parse_laws(fname, text):
    headings = []
    for m in HEADING.finditer(text):
        lm = LAW_HEADING.match(m.group(0))
        headings.append({'pos': m.start(), 'end': m.end(), 'level': len(m.group(1)),
                         'law': (lm.group(2), lm.group(3).strip()) if lm else None})
    laws = []
    for i, h in enumerate(headings):
        if not h['law']:
            continue
        stop = len(text)
        for j in range(i + 1, len(headings)):
            n = headings[j]
            if n['law'] or n['level'] <= h['level']:
                stop = n['pos']
                break
        laws.append({'file': fname, 'cred': CRED_OF_FILE[fname], 'id': h['law'][0],
                     'title': h['law'][1], 'body': text[h['end']:stop]})
    return laws


def split_elements(body):
    marks = list(ELEMENT_MARK.finditer(body))
    out = {}
    for i, m in enumerate(marks):
        stop = marks[i + 1].start() if i + 1 < len(marks) else len(body)
        out[int(m.group(1))] = body[m.end():stop].strip()
    return out


def load():
    laws = []
    for f in LAW_FILES:
        for law in parse_laws(f, read(os.path.join(HERE, f))):
            law['el'] = split_elements(law['body'])
            laws.append(law)
    return laws


def flat(s):
    return ' '.join((s or '').split())


def plain(s):
    """Strip markdown emphasis and code ticks for table cells."""
    s = flat(s)
    s = s.replace('|', '\\|')
    return s


def ids(seq):
    return ' · '.join('`%s`' % x for x in seq)


