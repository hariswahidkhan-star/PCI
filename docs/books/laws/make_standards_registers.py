"""make_standards_registers.py — generates the four derived registers over the PCI Standards.

Plain Python 3, no third-party imports. Run from anywhere:

    python3 docs/books/laws/make_standards_registers.py

It reads the four law files, parses all 113 laws into their twenty-five Manual §5 elements, and
writes:

  * PCI_STANDARDS_DEFINITIONS_REGISTER.md      — the canonical definitions, from the table in §DEFS below
                                           joined to element 4 of every law (which laws rely on it)
  * PCI_STANDARDS_COMPLIANCE_TEST_CATALOGUE.md — element 21 of every law
  * PCI_STANDARDS_EVIDENCE_REGISTER.md         — element 7 of every law
  * PCI_STANDARDS_EXTERNAL_AUTHORITY_MATRIX.md — element 17 of every law, cross-checked against
                                           ../registries/EXTERNAL_AUTHORITIES.md
  * PCI_STANDARDS_EXAMINATION_BLUEPRINT.md     — element 24 of every law

Everything that can be counted is counted here rather than transcribed. Two columns cannot be
counted and are carried as reviewed tables in this file, each row with its reason, so that a human
can audit and re-run them:

  * JUDGEMENT — which element 21 tests depend on the reviewer's judgement (catalogue, last column).
  * The canonical definitions and the record of what each file previously said (definitions
    register). The register's "which laws rely on it" column is computed, not asserted.

Re-run after any edit to a law file. The registers go stale the moment the laws move.
"""

