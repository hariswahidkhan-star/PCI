def clean_phrase(s, limit=110):
    s = flat(s)
    s = re.sub(r'\*\*|\*|`', '', s)
    s = re.sub(r'\s*\([^)]*\)', '', s)
    s = s.strip(' .,;:—')
    if len(s) > limit:
        s = s[:limit].rsplit(' ', 1)[0] + '…'
    return s


