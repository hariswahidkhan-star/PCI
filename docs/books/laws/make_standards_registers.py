def records_named(el21):
    t = re.sub(r'\*\*|\*|`', '', flat(el21)).lower()
    found = []
    for m in RECORD_RE.finditer(t):
        phrase = ' '.join(m.group(1).split())
        if NOT_A_RECORD.search(phrase):
            continue
        if phrase in GENERIC_RECORD or len(phrase) < 5:
            continue
        if any(f == phrase or f.endswith(' ' + phrase) for f in found):
            continue
        found = [f for f in found if not phrase.endswith(' ' + f)]
        found.append(phrase)
    if not found:
        # Accept a bare generic record word rather than inventing one.
        for m in RECORD_RE.finditer(t):
            p = ' '.join(m.group(1).split())
            if p and p not in found:
                found.append(p)
    return '; '.join(found[:6]) if found else 'the retained working record'


