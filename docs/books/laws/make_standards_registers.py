    flagged = [l for l in laws if l['id'] in JUDGEMENT]
    n = len(laws)
    by_cred = Counter(l['cred'] for l in flagged)
    asserts = [l for l in laws if REPRO.search(l['el'].get(21, ''))]
    both = [l for l in flagged if REPRO.search(l['el'].get(21, ''))]

