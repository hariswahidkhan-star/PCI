# ---------------------------------------------------------------------------- 5. blueprint

def build_blueprint(laws):
    rows = []
    for l in laws:
        e24 = l['el'].get(24, '')
        rows.append({'law': l, 'modes': modes_of(e24), 'cog': cognitive_of(e24)})
    mode_count = Counter()
    mode_by_cred = defaultdict(Counter)
    for r in rows:
        for m in r['modes']:
            mode_count[m] += 1
            mode_by_cred[r['law']['cred']][m] += 1
    nomode = [r['law']['id'] for r in rows if not r['modes']]
    single_mode = [r['law']['id'] for r in rows if len(r['modes']) == 1]
    cred_totals = Counter(l['cred'] for l in laws)

    out = [header(
        'PCI Standards Examination Blueprint',
        'It is element 24 — examination application — of all 113 PCI Standards: which '
        'assessment mode each law states, at what cognitive level, and for which credential’s '
        'examination.',
        'It was derived by extracting element 24 from each law and matching it against the six '
        'assessment modes Drafting Manual §5 names. **It contains no examination items.** A '
        'blueprint states what may be assessed and how; live items are kept separate, and putting '
        'them in a derived register that is regenerated on every edit would compromise them.')]

    out.append('## 1. Summary\n\n| | Count |\n|---|---|\n')
    out.append('| Laws with an assessment mode stated | **%d** of %d |\n'
               % (len(laws) - len(nomode), len(laws)))
    out.append('| Laws stating exactly one mode | **%d** |\n' % len(single_mode))
    out.append('| Mode assignments in total | **%d** (mean %.1f per law) |\n'
               % (sum(mode_count.values()), float(sum(mode_count.values())) / len(laws)))
    out.append('| Laws stating a cognitive level | **0** |\n')
    out.append('\n**Every one of the 113 laws states at least one assessment mode.** That is the '
               'blueprint’s strongest finding and it is unusual: the commonest failure in a '
               'competence framework is a requirement nobody can assess, and this corpus does not '
               'have one.\n\n'
               '**No law states a cognitive level.** Element 24 names the *mode* and the *case*, '
               'never the level of cognition demanded. The Cognitive level column below is therefore '
               '**derived, not extracted** — by the rule in §3 — and it is the one column in this '
               'blueprint that an examination designer must review rather than adopt.\n\n')

    out.append('## 2. Coverage — which modes are over- and under-used\n\n'
               '| Assessment mode | Laws | Share | FND | PCL-AI | PFL-AI | PML-AI |\n'
               '|---|---|---|---|---|---|---|\n')
    for m in MODES:
        c = mode_count[m]
        out.append('| %s | **%d** | %.0f%% | %d | %d | %d | %d |\n'
                   % (m, c, 100.0 * c / len(laws), mode_by_cred['FND'][m], mode_by_cred['PCL'][m],
                      mode_by_cred['PFL'][m], mode_by_cred['PML'][m]))
    out.append('\n')

    ordered = mode_count.most_common()
    over, second = ordered[0], ordered[1]
    pct = lambda c: 100.0 * c / len(laws)
    out.append('**Over-used: %s (%d laws, %.0f%%), with %s close behind (%d, %.0f%%).** More than '
               'two-thirds of the corpus is assessed the same way. A blueprint in which one mode '
               'carries that share produces an examination rewarding one skill — reading a situation '
               'and choosing a course — and under-testing the rest.\n\n'
               % (over[0], over[1], pct(over[1]), second[0], second[1], pct(second[1])))
    ai = mode_count['AI-verification case']
    esc = mode_count['escalation decision']
    out.append('**Most under-used: the AI-verification case (%d laws, %.0f%%).** This is the '
               'striking one. The corpus’s governing principle is *AI proposes; the professional '
               'verifies, decides and remains accountable*; every one of the 113 laws carries '
               'elements 14, 15 and 16 on AI; and **element 16 (AI verification) is normative**, so '
               'a breach of it is a breach of the law. The mode that tests it is stated in %.0f per '
               'cent of them. The gap between what the corpus regulates and what it examines is '
               'widest here.\n\n' % (ai, pct(ai), pct(ai)))
    out.append('**Second under-used: the escalation decision (%d laws, %.0f%%).** Escalation is the '
               'act several of the most important laws exist to compel — `PCI-FND-STD-11` is an '
               'entire law about it, `D-10` and `D-20` define when it starts and how fast it must '
               'travel, and three of the red team’s closed findings (**C-13**, **C-14**, '
               '**U-8**) were escalation thresholds with no clock. A corpus that makes escalation '
               'central and assesses it in %d of %d laws is not examining what it says matters '
               'most.\n\n' % (esc, pct(esc), esc, len(laws)))

    out.append('## 3. How the cognitive level was derived\n\n'
               'No law states one, so the column is generated by this rule, applied in order to the '
               'element 24 text. It is a first cut for an examination designer, not a finding:\n\n'
               '| Level | Assigned when element 24 | \n|---|---|\n'
               '| **Evaluation** — weigh competing duties and defend a choice | poses an ethical '
               'dilemma, a conflict of duty, an instruction under pressure |\n'
               '| **Analysis** — locate the defect in a body of material | asks the candidate to '
               'locate, identify, distinguish or diagnose within a scenario |\n'
               '| **Application** — apply a stated rule or method to a case | asks for a '
               'recomputation, a reproduction, a selection or an escalation decision |\n'
               '| **Comprehension** — recognise the correct record or route | does none of the above '
               '|\n\n'
               '**Recall is deliberately absent.** Manual §5 element 24 ends "not by memorising law '
               'numbers", and no element 24 in the corpus invites recall. That is a strength worth '
               'stating.\n\n')

    thin = min(CERT_FILES, key=lambda c: sum(mode_by_cred[c].values()) / float(cred_totals[c]))
    out.append('## 4. Which credential has the thinnest law coverage in its examination\n\n'
               '| Credential | Laws | Mode assignments | Mean modes per law | Modes never used |\n'
               '|---|---|---|---|---|\n')
    for cred in ['FND'] + list(CERT_FILES):
        used = mode_by_cred[cred]
        never = [m for m in MODES if not used[m]]
        out.append('| %s | %d | %d | **%.2f** | %s |\n'
                   % (CRED_NAME[cred], cred_totals[cred], sum(used.values()),
                      float(sum(used.values())) / cred_totals[cred],
                      ', '.join(never) if never else '— none' ))
    out.append('\n**%s carries the thinnest coverage** on modes per law. A credential whose laws are '
               'assessed through fewer routes is examined more narrowly, and a candidate can pass by '
               'being good at one thing. Note that the foundational laws are examined **inside all '
               'three** credential examinations, so their modes are counted once here and delivered '
               'three times in practice.\n\n' % CRED_NAME[thin])

    out.append('---\n\n## 5. The blueprint\n\n')
    for cred in ['FND'] + list(CERT_FILES):
        group = [r for r in rows if r['law']['cred'] == cred]
        out.append('### %s — %d laws\n\n' % (CRED_NAME[cred], len(group)))
        out.append('| Law | Official title | Assessment mode stated | Cognitive level (derived) | '
                   'Which examination |\n|---|---|---|---|---|\n')
        for r in group:
            which = ('All three — PCL-AI, PFL-AI and PML-AI' if cred == 'FND'
                     else CRED_NAME[cred] + ' only')
            out.append('| `%s` | %s | %s | %s | %s |\n'
                       % (r['law']['id'], plain(r['law']['title']),
                          plain(' · '.join(r['modes']) if r['modes'] else '**none stated**'),
                          plain(r['cog']), which))
        out.append('\n')

    out.append('---\n\n## 6. What this blueprint deliberately does not contain\n\n'
               '**No examination items, item stems, distractors, marking keys or worked scenarios.** '
               'Element 24 of each law describes the *shape* of a case — "an instruction to leave '
               'that one until next month from a person senior to the candidate" — and that '
               'description is reported here as the law states it. Turning any of them into a live '
               'item is a separate exercise, kept in a separate place, on a different access '
               'control. A blueprint is regenerated on every edit to a law file; live items must not '
               'be.\n\n'
               '---\n\n*Derived blueprint. Not a PCI Law; creates no obligation.*\n\n'
               '> **AI proposes; the professional verifies, decides and remains accountable.**\n')
    return write('PCI_STANDARDS_EXAMINATION_BLUEPRINT.md', ''.join(out))


